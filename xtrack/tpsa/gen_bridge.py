"""gen_bridge.py -- The bridge between c_src/xt_bridge.cpp and xtrack.

Driven by an ``ELEMENTS`` list, outputs every artifact that crosses the C/Python
boundary. Nothing on both sides of the boundary is manually duplicated: struct, element
accessors, dispatch switch and the Python registry all come from here.

    python -m xtrack.tpsa.gen_bridge     # writes c_src/generated/ + registry.py

The GTPSA engine ABI is not emitted here: it belongs to the standalone ``xgtpsa``
package (``xgtpsa._cffi.CDEF``), which holds nothing xtrack-derived.
"""

import os
import re

import xtrack as xt
from xobjects.context import sort_classes
from xobjects.specialize_source import specialize_source
from xtrack.tpsa._bridge_particle import XtBridgeParticle
from xtrack.tpsa._tpsa_monitor import XtBridgeTpsaMonitor

HERE = os.path.dirname(os.path.abspath(__file__))
GEN = os.path.join(HERE, "c_src", "generated")

BANNER = "/* AUTO-GENERATED by gen_bridge.py -- do not edit. */\n"
PY_BANNER = "# AUTO-GENERATED by xtrack/tpsa/gen_bridge.py -- do not edit.\n"

# ---------------------------------------------------------------------------- #
# Registry: element classes the bridge supports and their physics headers.
# ---------------------------------------------------------------------------- #
