# ---------------------------------------------------------------------------- #
# Knob-dependent strength fields are those whose C chain is XT_STRENGTH-retyped, so their
# getter may safely a TPSA. Not a list of what is actually knobbed. Adding an
# entry means doing that retype first. k0s is absent as no registered class carries it.
#
# In tpsa_param every listed field returns mad::tpsa, knobbed or not, since a getter has
# one return type per module. The runtime lookup in xt_knob() then decides per instance:
# hit gives the parametric TPSA, miss a constant one. Unknobbed elements therefore pay
# TPSA arithmetic for nothing, the ~5% constant-lift tax that per-element dispatch would
# remove. The num and tpsa flavors define the wrapper away to the raw double getter.
# ---------------------------------------------------------------------------- #
KNOB_DEPENDENT_FIELDS = ["k0", "k1", "k2", "k3", "k1s", "k2s", "k3s", "ks"]

# ---------------------------------------------------------------------------- #
# Particle-variable classification (drives struct, cdef, accessors).
# Every key must exist in xtrack's Particles var lists (asserted below).
# A new upstream field forces a classification here instead of silent drift.
# ---------------------------------------------------------------------------- #
COORD_VARS = ["x", "px", "y", "py", "zeta", "delta"]  # XT_NUM, map variables
DERIVED_VARS = ["ptau", "rvv", "rpp", "s"]  # XT_NUM, C-owned
LOCAL_VARS = ["ax", "ay"]  # XT_NUM, C-owned, not in ABI as they're handled locally
REF_VARS = [
    "q0",
    "mass0",
    "beta0",
    "gamma0",
    "p0c",
    "chi",
    "charge_ratio",
    "weight",
    "anomalous_magnetic_moment",
]  # double
INT_VARS = ["state", "at_element"]  # int64_t
EXCLUDED = [
    "t_sim",
    "spin_x",
    "spin_y",
    "spin_z",
    "pdg_id",
    "particle_id",
    "at_turn",
    "parent_particle_id",
    "_rng_s1",
    "_rng_s2",
    "_rng_s3",
    "_rng_s4",
    "_capacity",
    "_num_active_particles",
    "_num_lost_particles",
    "start_tracking_at_element",
]


def _assert_var_classification():
    from xtrack.particles import particles as _p

    allvars = set()
    for lst in (_p.size_vars, _p.scalar_vars, _p.per_particle_vars):
        allvars |= {name for _, name in lst}
    classified = COORD_VARS + DERIVED_VARS + LOCAL_VARS + REF_VARS + INT_VARS + EXCLUDED
    assert len(classified) == len(set(classified)), "duplicate var in classification"
    missing = allvars - set(classified)
    extra = set(classified) - allvars
    assert not missing, (
        f"unclassified Particles vars -- classify in gen_bridge.py: {sorted(missing)}"
    )
    assert not extra, (
        f"gen_bridge classifies vars absent from Particles: {sorted(extra)}"
    )
    # The xo.Struct must carry exactly COORD + REF + line_length + INT +
    # track_flags. Single source of truth for the C struct + cdef, so a deviation is caught here.
    struct_fields = [f.name for f in XtBridgeParticle._fields]
    expected = COORD_VARS + REF_VARS + ["line_length"] + INT_VARS + ["track_flags"]
    assert set(struct_fields) == set(expected), (
        f"XtBridgeParticle fields {sorted(struct_fields)} != {sorted(expected)}"
    )


def _sorted_elements():
    # Same convention as _element_ref_data_class_from_element_classes (sort by the
    # dressed class name) so our typeids match the ElementRefData UnionRef order.
    return sorted(ELEMENTS, key=lambda c: c._XoStruct._DressingClass.__name__)


def type_ids():
    return {c.__name__: i for i, c in enumerate(_sorted_elements())}


