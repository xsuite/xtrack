def make_line(nstep=10, ny=3):
    """Build the ring; nstep is the RK4 step count per dipole spline segment."""
    prototypes = [xt.BFieldExpansion(
        length=length, h=h, knc=knc, ksc=np.zeros((1, 4)), ksol=np.zeros(4),
        ny=ny, nstep=nstep, pkin_const=False)
        for length, h, knc in DIPOLE_SEGMENTS]
    np.testing.assert_allclose(sum(el.length for el in prototypes), DIPOLE_LENGTH,
                               rtol=0, atol=1e-14)
    np.testing.assert_allclose(sum(el.angle for el in prototypes), BEND_ANGLE,
                               rtol=0, atol=1e-14)

    # Keep the CERNbox element positions; cycle to qb1 to avoid cutting a fringe
    # at the ring boundary. The straight fringe extensions replace nearby drift.
    placements = []
    for cell in range(3):
        offset = cell * CELL_LENGTH
        for name, centre, length, k1 in QUADRUPOLES:
            start = (offset + centre - length / 2 - START_S) % CIRCUMFERENCE
            name = f'{name[:2]}{cell + 1}{name[2:]}'
            placements.append((start, name, [xt.Quadrupole(length=length, k1=k1)]))
        for suffix, entrance in (('a', 0.2), ('b', MAGNETIC_LENGTH + 1.8)):
            start = (offset + entrance - FRINGE_EXTENT - START_S) % CIRCUMFERENCE
            placements.append((start, f'mb{cell + 1}{suffix}',
                               [el.copy() for el in prototypes]))

    elements = {}
    cursor = 0.
    for index, (start, name, magnets) in enumerate(sorted(placements)):
        assert start >= cursor - 1e-12, f'Overlapping element: {name}'
        if start > cursor:
            elements[f'drift_{index}'] = xt.Drift(length=start - cursor)
        for i, element in enumerate(magnets):
            elements[f'{name}.{i:02d}' if len(magnets) > 1 else name] = element
        cursor = start + sum(el.length for el in magnets)
    assert cursor <= CIRCUMFERENCE + 1e-12
    elements['drift_end'] = xt.Drift(length=CIRCUMFERENCE - cursor)
    line = xt.Line(elements=elements)
    line.particle_ref = xt.Particles(mass0=MASS0, q0=2,
                                     energy0=MASS0 + KINETIC_ENERGY)
    line.configure_drift_model(model='exact')
    return line
