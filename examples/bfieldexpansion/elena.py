def make_line(nstep=10, num_phi='auto'):
    """Build the ring; nstep is the RK4 step count per dipole spline segment.

    num_phi='auto' retains the complete straight-field polynomial and terms
    linear in curvature. Use an integer to study higher curvature orders.
    """
    prototypes = [xt.BFieldExpansion(
        length=length, h=h, knc=knc, ksc=np.zeros((1, 4)), ksol=np.zeros(4),
        num_phi=num_phi, nstep=nstep, pkin_const=False)
        for length, h, knc in DIPOLE_SEGMENTS]
    np.testing.assert_allclose(sum(el.length for el in prototypes), DIPOLE_LENGTH,
                               rtol=0, atol=1e-14)
    np.testing.assert_allclose(sum(el.angle for el in prototypes), BEND_ANGLE,
                               rtol=0, atol=1e-14)

    # Place powered elements at the original absolute positions, then cycle.
    placements = []
    section_start = 0.
    for bend, straight_length, quadrupoles in SECTIONS:
        for suffix, centre, k1 in quadrupoles:
            start = (section_start + centre - 0.125 - START_S) % CIRCUMFERENCE
            placements.append((start, f'lnr.mqnlg.{suffix}',
                               [xt.Quadrupole(length=0.25, k1=k1)]))
        start = (section_start + straight_length - FRINGE_EXTENT - START_S) % CIRCUMFERENCE
        placements.append((start, f'lnr.mbhek.{bend}', [el.copy() for el in prototypes]))
        section_start += straight_length + MAGNETIC_LENGTH

    elements = {'lnr.vvgbf.0114': xt.Marker()}
    cursor = 0.
    for index, (start, name, magnets) in enumerate(sorted(placements)):
        assert start >= cursor - 1e-12, f'Overlapping element: {name}'
        if start > cursor:
            elements[f'drift_{index}'] = xt.Drift(length=start-cursor)
        for i, element in enumerate(magnets):
            elements[f'{name}.{i:02d}' if len(magnets) > 1 else name] = element
        cursor = start + sum(el.length for el in magnets)
    elements['drift_end'] = xt.Drift(length=CIRCUMFERENCE-cursor)
    line = xt.Line(elements=elements)
    line.particle_ref = xt.Particles(p0c=P0C, mass0=xt.PROTON_MASS_EV, q0=-1)
    line.configure_drift_model(model='exact')
    return line
